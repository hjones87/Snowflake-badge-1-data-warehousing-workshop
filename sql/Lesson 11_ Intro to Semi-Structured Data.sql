----LESSON 11: INTRO TO SEMI-STRUCTURED DATA----

--- CREATE JSON TABLE & FILE FORMATS, LOAD FILES ---

--1) create table raw JSON data

USE DATABASE library_card_catalog;
USE SCHEMA PUBLIC;
USE ROLE SYSADMIN;

CREATE TABLE AUTHOR_INGEST_JSON (
    RAW_AUTHOR VARIANT
);

--2) create file format for JSON data

CREATE FILE FORMAT JSON_FILE_FORMAT
TYPE = 'JSON'
COMPRESSION = 'AUTO'
ENABLE_OCTAL = FALSE
ALLOW_DUPLICATE = FALSE
STRIP_OUTER_ARRAY = TRUE
STRIP_NULL_VALUES = FALSE
IGNORE_UTF8_ERRORS = FALSE;

--check correct file format
SELECT $1
FROM @util_db.public.my_internal_stage/author_with_header.json
(file_format => JSON_FILE_FORMAT);

--COPY INTO table
COPY INTO LIBRARY_CARD_CATALOG.PUBLIC.AUTHOR_INGEST_JSON
FROM @UTIL_DB.PUBLIC.MY_INTERNAL_STAGE
FILES = ( 'author_with_header.json')
FILE_FORMAT = ( FORMAT_NAME=LIBRARY_CARD_CATALOG.PUBLIC.JSON_FILE_FORMAT);

--check table loaded correctly
SELECT *
FROM AUTHOR_INGEST_JSON;

---QUERY JSON TABLE---

--returns AUTHOR_UID value form top-level objects's attribute
SELECT RAW_AUTHOR:AUTHOR_UID
FROM AUTHOR_INGEST_JSON;

--returns data in a way that makes it look like normalised table 
SELECT
    RAW_AUTHOR:AUTHOR_UID,
    RAW_AUTHOR:FIRST_NAME::STRING AS FIRST_NAME,
    RAW_AUTHOR:MIDDLE_NAME::STRING AS MIDDLE_NAME,
    RAW_AUTHOR:LAST_NAME::STRING AS LAST_NAME,
FROM AUTHOR_INGEST_JSON;